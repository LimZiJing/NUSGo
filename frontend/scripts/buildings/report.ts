import type { BuildingAlias } from './aliases.ts'
import { DISTANCE_WARNING_METRES, type BuildCatalogueResult } from './catalogue.ts'

export type ReportContext = {
  readonly snapshotFile: string
  readonly aliases: readonly BuildingAlias[]
}

function ukDate(isoDate: string): string {
  const [year, month, day] = isoDate.split('-')
  return `${day}/${month}/${year}`
}

/** Pipes would break a Markdown table cell. */
function cell(value: string): string {
  return value.replace(/\|/g, '\\|')
}

function section(title: string, body: readonly string[], empty: string): string[] {
  return [`## ${title}`, '', ...(body.length > 0 ? body : [empty]), '']
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  if (rows.length === 0) return []
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((row) => `|${row.map((value) => (value ? ` ${cell(value)} ` : ' ')).join('|')}|`),
  ]
}

/** The dedupe report: everything the import linked, skipped or doubted, so nothing merges silently. */
export function renderReport(result: BuildCatalogueResult, context: ReportContext): string {
  const { catalogue, findings } = result
  const byId = new Map(catalogue.buildings.map((building) => [building.id, building]))
  const label = (id: string) => `${byId.get(id)?.name ?? id} (\`${id}\`)`
  const ids = (list: readonly string[]) => list.map((id) => `\`${id}\``).join(', ')
  const evidence = new Map(context.aliases.map((alias) => [alias.prefix, alias.evidence]))

  const ruleCounts = (['override', 'code', 'alias', 'name'] as const).map((rule) => (
    [rule, String(findings.links.filter((link) => link.rule === rule).length)]
  ))
  const reviewedLinks = findings.links
    .filter((link) => link.rule !== 'code')
    .map((link) => [link.prefix, label(link.buildingId), link.rule, String(link.roomCount), evidence.get(link.prefix) ?? ''])
  const multiAddressGroups = findings.repeatedNames.filter((group) => group.addresses.length > 1)

  const needsReview = [
    ...findings.ambiguous.map((match) => `- Ambiguous match for ${match.prefix}; pick a record with an override.`),
    ...findings.distanceWarnings.map((warning) => (
      `- ${warning.prefix} is ${warning.metres} m from ${label(warning.buildingId)}; check the link or the centroid.`
    )),
    ...multiAddressGroups.map((group) => (
      `- Repeated name "${group.name}" spans ${group.addresses.length} addresses; consider separate groupKeys.`
    )),
    ...findings.sharedCoordinates.map((group) => `- Records share one point and may be duplicates: ${ids(group)}.`),
    ...findings.staleAliases.map((issue) => `- Alias ${issue}`),
    ...findings.dataIssues.map((issue) => `- ${issue}`),
    ...(findings.unlinkedPrefixes.length > 0
      ? [`- ${findings.unlinkedPrefixes.length} room prefixes have no building (see below).`]
      : []),
  ]

  const withoutRooms = findings.buildingsWithoutRooms
  const lines = [
    '# NUS Digital Twin buildings: dedupe report',
    '',
    `Generated by \`npm run buildings:import\` from \`${context.snapshotFile}\` (fetched on ${ukDate(catalogue.source.fetchedOn)}), ` +
      '`frontend/public/data/venues.json`, the alias table in `frontend/scripts/buildings/aliases.ts` and ' +
      '`scripts/data/building-overrides.json`. Do not edit by hand; re-run the import instead.',
    '',
    'Each room-code prefix is linked by the first confident rule: override, exact code, alias, then a unique ' +
      `building name at the start of room names. Proximity never links; a match more than ${DISTANCE_WARNING_METRES} m ` +
      'from the median of its rooms is flagged. Building locations are API centroids, except buildings marked provisional-entrance, which use an unverified OpenStreetMap entrance.',
    '',
    ...section('Counts', table(['Measure', 'Count'], [
      ['API records', String(findings.counts.apiRecords)],
      ['Buildings written', String(findings.counts.buildingsWritten)],
      ['Rooms linked', String(findings.counts.roomsLinked)],
      ['Rooms unlinked', String(findings.counts.roomsUnlinked)],
    ]), ''),
    ...section('Prefix links by rule', [
      ...table(['Rule', 'Prefixes'], ruleCounts),
      ...(reviewedLinks.length > 0 ? ['', 'Links not made by exact code:', ''] : []),
      ...table(['Prefix', 'Building', 'Rule', 'Rooms', 'Evidence'], reviewedLinks),
    ], 'No prefixes were linked.'),
    ...section('Needs review', needsReview, 'Nothing needs review.'),
    ...section('Ambiguous matches (not linked)', findings.ambiguous.map((match) => (
      `- ${match.prefix} (${match.rule} rule): ${ids(match.buildingIds)}`
    )), 'None.'),
    ...section(`Distance warnings (over ${DISTANCE_WARNING_METRES} m)`, findings.distanceWarnings.map((warning) => (
      `- ${warning.prefix}: ${label(warning.buildingId)} is ${warning.metres} m from the median of its rooms`
    )), 'None.'),
    ...section('Room prefixes with no building', [
      ...(findings.unlinkedPrefixes.length > 0
        ? ['The nearest building is a review hint only; it is never used as a link.', '']
        : []),
      ...table(['Prefix', 'Rooms', 'Note', 'Nearest building (hint)'], findings.unlinkedPrefixes.map((entry) => [
        entry.prefix,
        String(entry.roomCount),
        entry.note ?? '',
        entry.nearest ? `${label(entry.nearest.buildingId)}, ${entry.nearest.metres} m` : '',
      ])),
    ], 'None.'),
    ...section('API buildings with no linked rooms', withoutRooms.length > 0
      ? [
          `${withoutRooms.length} of ${findings.counts.buildingsWritten} API buildings have no linked rooms ` +
            '(expected for residences, halls and facilities without teaching rooms):',
          '',
          withoutRooms.map((id) => byId.get(id)?.name ?? id).join('; ') + '.',
        ]
      : [], 'None.'),
    ...section('Repeated API names', [
      ...(findings.repeatedNames.length > 0
        ? ['Each record stays a separate building; records sharing a normalised name share a `groupKey`.', '']
        : []),
      ...table(['Name', 'groupKey', 'Records', 'Addresses'], findings.repeatedNames.map((group) => [
        group.name, `\`${group.groupKey}\``, String(group.buildingIds.length), group.addresses.join('; '),
      ])),
    ], 'None.'),
    ...section('API records sharing coordinates', findings.sharedCoordinates.map((group) => `- ${ids(group)}`), 'None.'),
    ...section('Standalone-venue candidates', [
      ...(findings.standaloneCandidates.length > 0
        ? ['Venues whose code equals a building code, or that have no room structure (input for #261).', '']
        : []),
      ...table(['Venue', 'Reason'], findings.standaloneCandidates.map((entry) => [entry.venueCode, entry.reason])),
    ], 'None.'),
  ]
  return `${lines.join('\n').trimEnd()}\n`
}
